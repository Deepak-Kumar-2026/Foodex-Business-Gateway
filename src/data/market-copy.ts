export type MarketVars = Record<string, string | number>;

/** Returns a translator bound to a language and a set of placeholder values. */
export function marketCopy(lang: LangCode, vars: MarketVars) {
  const dict = dicts[lang];
  return (key: MarketCopyKey) => {
    const template = dict?.[key] ?? en[key];
    return template.replace(/\{(\w+)\}/g, (m, k: string) => String(vars[k] ?? m));
  };
}

